# Туристические агентства предлагают следующие туры.
# Вояж - Мексика, Канада, Израиль, Италия.
# РейнаТур - Англия, Япония, Канада, ЮАР. Определить:
# 1. какие туры из Вояж отсутствуют в РейнаТур.
# 2. какие туры из РейнаТур отсутствуют в Вояж.
# 3. перечень одинаковых туров.
# 4. равны ли перечни туров.

voyage = {'Мексика', 'Канада', 'Израиль', 'Италия'}
reina_tour = {'Англия', 'Япония', 'Канада', 'ЮАР'}

print('туры из Вояж, отсутствующие в РейнаТур: ', voyage - reina_tour)
print('туры из РейнаТур, отсутствующие в Вояж: ', reina_tour - voyage)
print('перечень одинаковых туров: ', voyage & reina_tour)

if voyage == reina_tour:
    print('перечни туров равны')
else:
    print('перечни туров не равны')