# Дано целое число А.
# Проверить истинность высказывания "Число А является нечетным"

a = input("Введите целое число: ")

while type(a) != int: # обработка исключений
    try:
        a = int(a)
    except ValueError:
        print("Неправильно ввели!")
        a = input("Введите целое число: ")

print(a % 2 != 0)
